async def generate():
    for persona_id, cfg in PERSONAS.items():
        for key, text in LINES[persona_id].items():
            path = OUT / persona_id / f'{key}.mp3'
            path.parent.mkdir(parents=True, exist_ok=True)
            if path.exists() and path.stat().st_size > 1000:
                print(f'skip {path.parent.name}/{path.name}')
                continue
            await render(text, cfg, path)
            await asyncio.sleep(0.4)  # не ддосим сервис
    missing = [f'{p}/{k}' for p in PERSONAS for k in LINES[p]
               if not (OUT / p / f'{k}.mp3').exists() or (OUT / p / f'{k}.mp3').stat().st_size < 1000]
    print('MISSING:', missing if missing else 'none')


async def render(text, cfg, path, attempts=4):
    for attempt in range(1, attempts + 1):
        try:
            tts = edge_tts.Communicate(text, cfg['voice'], rate=cfg['rate'], pitch=cfg['pitch'])
            await tts.save(str(path))
            print(f'ok  {path.parent.name}/{path.name}  {path.stat().st_size // 1024} KB')
            return
        except Exception as e:
            if attempt == attempts:
                print(f'FAIL {path.parent.name}/{path.name}: {type(e).__name__}')
                return
            print(f'retry {attempt} ({type(e).__name__}) → {path.parent.name}/{path.name}')
            await asyncio.sleep(1.5 * attempt)


if __name__ == '__main__':
    asyncio.run(generate())
